CREATE TABLE IF NOT EXISTS report_schedule (
 id INT PRIMARY KEY, enabled TINYINT NOT NULL DEFAULT 0,
 frequency VARCHAR(10) NOT NULL DEFAULT 'daily', send_time TIME NOT NULL DEFAULT '08:00:00',
 next_run DATETIME NULL
) ENGINE=InnoDB;
INSERT IGNORE INTO report_schedule(id) VALUES(1);
CREATE TABLE IF NOT EXISTS report_runs (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, due_at DATETIME NOT NULL UNIQUE,
 recipient VARCHAR(254) NOT NULL, subject VARCHAR(200) NOT NULL, body MEDIUMTEXT NOT NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'pending', attempts INT NOT NULL DEFAULT 0,
 next_attempt DATETIME NOT NULL, sent_at DATETIME NULL, last_error VARCHAR(255) NULL
) ENGINE=InnoDB;
